/**
 * Get coordinates for a specific neighborhood in a city.
 * Falls back to city center coordinates if neighborhood not found.
 */
export function getNeighborhoodCoords(
    citySlug: string, 
    neighborhoodNameAr: string,
    fallbackLat: number,
    fallbackLng: number
): { lat: number; lng: number } {
    const cityCoords = NEIGHBORHOOD_COORDS[citySlug];
    if (cityCoords && cityCoords[neighborhoodNameAr]) {
        return cityCoords[neighborhoodNameAr];
    }
    return { lat: fallbackLat, lng: fallbackLng };
}
